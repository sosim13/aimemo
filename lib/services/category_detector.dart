  static bool isValid(String name) {
    final trimmed = name.trim();
    if (all.contains(trimmed)) return true;
    // Allow partial match for &-separated categories
    for (final cat in all) {
      if (cat.replaceAll(' & ', ' ').toLowerCase() ==
          trimmed.replaceAll(' & ', ' ').toLowerCase()) {
        return true;
      }
    }
    return false;
  }

  /// Normalize a category string to the canonical form
  static String? normalize(String name) {
    final trimmed = name.trim();
    if (all.contains(trimmed)) return trimmed;
    for (final cat in all) {
      if (cat.replaceAll(' & ', ' ').toLowerCase() ==
          trimmed.replaceAll(' & ', ' ').toLowerCase()) {
        return cat;
      }
    }
    return null;
  }
}

