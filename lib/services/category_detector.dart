  static const List<String> categoryNames = AppCategories.all;

  /// Detect the most likely category based on keyword matching in the text.
  /// Returns one of the known category names, or null if no clear match.
  static String? detect(String text) {
    if (text.isEmpty) return null;

    final scores = <String, int>{};

    for (final entry in _keywords.entries) {
      for (final keyword in entry.value) {
        if (_has(text, keyword)) {
          scores[entry.key] = (scores[entry.key] ?? 0) + 1;
        }
      }
    }

    // Also check if the text literally contains the category name
    // (e.g. transcript that mentions "게임" or "음악")
    for (final cat in AppCategories.all) {
      if (cat == '기타') continue;
      if (_has(text, cat)) {
        scores[cat] = (scores[cat] ?? 0) + 100; // very strong signal
      }
    }

    if (scores.isEmpty) return null;

    // Sort by score descending
    final entries = scores.entries.toList()
      ..sort((a, b) => b.value.compareTo(a.value));

    // Require at least score 2 for non-기타 categories (single keyword too weak)
    for (final e in entries) {
      if (e.key != '기타' && e.value >= 2) return e.key;
    }

    return null; // No confident match
  }
